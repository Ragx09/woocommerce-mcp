#!/usr/bin/env node
// GW-15 (REQ-DOD-07): one MCP client, two upstreams, both through the gateway /mcp.
// Reads recent WooCommerce orders (woo__list_orders) and files a GitHub issue with a summary
// (github__issue_write) in a throwaway repo the PAT may write to.
//
//   GITHUB_REPO=owner/repo node scripts/cross-server.mjs            # creates the issue, prints its URL
//   GITHUB_REPO=owner/repo node scripts/cross-server.mjs --dry-run  # lists + reads orders, prints the issue only
//
// Env: GATEWAY_URL (default http://app.127.0.0.1.nip.io/mcp), MCP_KEY (default: a temporary key for the
// seeded admin, created and revoked around the run — scripts/lib/gateway-key.mjs). Never printed.
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { withTempKey } from './lib/gateway-key.mjs';

const dryRun = process.argv.includes('--dry-run');
const gatewayUrl = process.env.GATEWAY_URL ?? 'http://app.127.0.0.1.nip.io/mcp';
const repoArg = process.env.GITHUB_REPO ?? '';
const [owner, repo] = repoArg.split('/');
if (!owner || !repo) {
  console.error('GITHUB_REPO=owner/repo is required (a throwaway repo: the script creates an issue there)');
  process.exit(2);
}

const text = (r) => r.content.filter((c) => c.type === 'text').map((c) => c.text).join('\n');
async function call(client, name, args) {
  const t0 = Date.now();
  const r = await client.callTool({ name, arguments: args });
  const ms = Date.now() - t0;
  if (r.isError) throw new Error(`${name} failed after ${ms} ms: ${text(r).slice(0, 300)}`);
  console.log(`ok   ${name} (${ms} ms)`);
  return text(r);
}

async function run(bearer) {
  const client = new Client({ name: 'cross-server', version: '1.0.0' });
  await client.connect(new StreamableHTTPClientTransport(new URL(gatewayUrl),
    { requestInit: { headers: { authorization: `Bearer ${bearer}` } } }));
  try {
    const names = new Set((await client.listTools()).tools.map((t) => t.name));
    for (const n of ['woo__list_orders', 'github__issue_write']) {
      if (!names.has(n)) throw new Error(`${n} is not listed by the gateway (is the upstream enabled and reachable?)`);
    }
    console.log(`ok   tools/list (${names.size} tools, woo + github present)`);

    const orders = JSON.parse(await call(client, 'woo__list_orders', { status: 'any', per_page: 20 }));
    const list = Array.isArray(orders) ? orders : (orders.orders ?? []);
    const byStatus = {};
    let total = 0;
    for (const o of list) {
      byStatus[o.status] = (byStatus[o.status] ?? 0) + 1;
      total += Number(o.total ?? 0);
    }
    const currency = list[0]?.currency ?? '';
    const stamp = new Date().toISOString().replace(/\.\d+Z$/, 'Z');
    const title = `Store order summary ${stamp} (${list.length} orders)`;
    const body = [
      `Generated by \`scripts/cross-server.mjs\` through the MCP gateway: \`woo__list_orders\` → \`github__issue_write\`.`,
      '',
      `- Orders read: ${list.length}`,
      `- By status: ${Object.entries(byStatus).map(([s, n]) => `${s} ${n}`).join(', ') || 'none'}`,
      `- Total value: ${total.toFixed(2)} ${currency}`.trimEnd(),
      '',
      '| Order | Date | Status | Total |',
      '|---|---|---|---|',
      ...list.slice(0, 10).map((o) => `| #${o.number ?? o.id} | ${String(o.date_created ?? '').slice(0, 10)} | ${o.status} | ${o.total} ${o.currency ?? ''} |`),
    ].join('\n');

    if (dryRun) {
      console.log(`dry-run: would create in ${owner}/${repo}:\n# ${title}\n${body}`);
    } else {
      const out = await call(client, 'github__issue_write', { method: 'create', owner, repo, title, body });
      const url = out.match(/https:\/\/github\.com\/[^\s"]+\/issues\/\d+/)?.[0];
      if (!url) throw new Error(`issue created but no URL in the answer: ${out.slice(0, 200)}`);
      console.log(`issue ${url}`);
    }
  } finally {
    await client.close();
  }
}

if (process.env.MCP_KEY) await run(process.env.MCP_KEY);
else await withTempKey('cross-server', run);
